"""Single maintained-product identity, deterministic source and PE generation.

The historical recovered version and independent scaffold wheel are not release
inputs. Explicit alternate version files are build inputs, including private CI
upgrade fixtures. They are recorded in provenance and never fetched at runtime.
"""
import argparse
from datetime import date
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PRODUCT_ID = 'cachecad-reconstructed'


def _unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('Duplicate version field')
        result[key] = value
    return result


def validate_identity(value):
    expected = {'schema_version', 'product_id', 'version', 'release_number', 'channel', 'build_date'}
    if not isinstance(value, dict) or set(value) != expected:
        raise ValueError('Invalid version identity fields')
    if type(value['schema_version']) is not int or value['schema_version'] != 1:
        raise ValueError('Unsupported version schema')
    if value['product_id'] != PRODUCT_ID or value['channel'] not in ('stable', 'beta'):
        raise ValueError('Unsupported product or channel')
    version = value['version']
    if not isinstance(version, str) or not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', version):
        raise ValueError('Version must contain three canonical numeric components')
    parts = tuple(map(int, version.split('.')))
    release = value['release_number']
    if any(part > 65535 for part in parts) or type(release) is not int or not 1 <= release <= 65535:
        raise ValueError('Version and release number must fit Windows PE WORDs')
    if not isinstance(value['build_date'], str) or date.fromisoformat(value['build_date']).isoformat() != value['build_date']:
        raise ValueError('Build date must be a canonical ISO date')
    return dict(value, windows_version=version + '.' + str(release))


def load_identity(path=None):
    path = Path(path) if path is not None else ROOT / 'version.json'
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 4096:
        raise ValueError('Version input must be a small regular file')
    return validate_identity(json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=_unique))


def generated_source(identity):
    """Only literal constants; no imports, environment or timestamp dependence."""
    values = {'APP_VERSION': identity['version'],
              'APP_RELEASE_NUMBER': identity['release_number'],
              'APP_WINDOWS_VERSION': identity['windows_version'],
              'APP_PRODUCT_ID': identity['product_id'],
              'APP_CHANNEL': identity['channel'],
              'APP_BUILD_DATE': identity['build_date'],
              'APP_IN_PRODUCTION': True, 'APP_IS_BETA': identity['channel'] == 'beta'}
    return ('"""Generated by tooling/version.py from the recorded version input. Do not edit."""\n'
            + ''.join(f'{name} = {value!r}\n' for name, value in values.items())).encode('utf-8')


def pe_resource(identity, *, filename='CacheCAD.exe', description='CacheCAD maintained application'):
    """PyInstaller VSVersionInfo input; validated values cannot inject source."""
    parts = tuple(map(int, identity['windows_version'].split('.')))
    strings = {'CompanyName': 'Local reconstruction development build',
               'FileDescription': description, 'FileVersion': identity['windows_version'],
               'InternalName': filename.removesuffix('.exe'), 'OriginalFilename': filename,
               'ProductName': 'CacheCAD Reconstructed', 'ProductVersion': identity['version']}
    entries = ',\n'.join(f'        StringStruct({name!r}, {value!r})' for name, value in strings.items())
    return (f'VSVersionInfo(ffi=FixedFileInfo(filevers={parts!r}, prodvers={parts!r}, '
            'mask=0x3f, flags=0, OS=0x40004, fileType=1, subtype=0, date=(0, 0)),\n'
            "  kids=[StringFileInfo([StringTable('040904B0', [\n" + entries
            + "\n  ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])])\n")


def previous_fixture(identity):
    """Create an explicit unsigned N fixture for upgrading to the current N+1 artifact."""
    value = {key: item for key, item in identity.items() if key != 'windows_version'}
    major, minor, patch = map(int, value['version'].split('.'))
    value['version'] = f'{major}.{minor}.{patch - 1}'
    value['release_number'] -= 1
    validate_identity(value)
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version-file', type=Path)
    parser.add_argument('--previous-fixture', type=Path,
                        help='Write an explicit synthetic prior-version identity for private CI only')
    args = parser.parse_args()
    identity = load_identity(args.version_file)
    if args.previous_fixture:
        with args.previous_fixture.open('x', encoding='utf-8') as stream:
            stream.write(json.dumps(previous_fixture(identity), indent=2, sort_keys=True) + '\n')
    else:
        print(json.dumps(identity, sort_keys=True))


if __name__ == '__main__':
    main()
